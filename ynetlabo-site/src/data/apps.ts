export type AppFeature = {
  readonly title: string;
  readonly body: string;
};

export type AppFaq = {
  readonly q: string;
  readonly a: string;
};

export type AppDetail = {
  /** URL の slug（/apps/<slug>） */
  readonly slug: string;
  /** consts.ts の PROJECTS[].name */
  readonly project: string;
  /** <title> に使う。検索されている言葉を頭に置く */
  readonly seoTitle: string;
  /** meta description */
  readonly seoDescription: string;
  /** H1 直下のリード */
  readonly lead: string;
  /** 「どんな人向けか」を1行で言い切る */
  readonly forWhom: readonly string[];
  readonly features: readonly AppFeature[];
  readonly faq: readonly AppFaq[];
  /** 対応プラットフォームの表示 */
  readonly platforms: readonly string[];
  /** 使い方ガイドの slug（src/content/guide/<id>） */
  readonly guide?: string;
  /** 関連記事を引くカテゴリ名（consts.ts の CATEGORY_SLUGS のキー） */
  readonly category?: string;
  /** ページ内で案内する自サイトのツール */
  readonly tools?: readonly { href: string; label: string }[];
};

